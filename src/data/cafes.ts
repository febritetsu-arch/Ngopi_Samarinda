function crowd(pattern: string): number[] {
  if (pattern.length !== 24 || /[^0-3]/.test(pattern)) {
    throw new Error(`Pola keramaian tidak valid: ${pattern}`);
  }
  return [...pattern].map((n) => Number(n));
}

